import { WallPrintError, finding, type Finding } from "./errors.ts";
import { findReservedAssuranceTerms, findSecretLike } from "./language.ts";
import { HEX64_RE, RECORD_ID_RE, WALLPRINT_VERSION } from "./vocabulary.ts";

/**
 * WallPrint portable reference: a locator for one committed WallPrint record.
 *
 *   WalletWall isn't always right. WallPrint keeps the record.
 *
 * A portable reference identifies WHICH record (the record id), WHICH bytes (the committed digest), WHICH WallPrint
 * contract version the record was committed under, and optionally WHICH section of the disclosure to open. It answers
 * nothing else: not whether any claim is true, not whether the asset is safe, not whether an issuer approved anything.
 * A reference is a locator, not authority; it carries no signature, names no signer, and becomes no more authoritative
 * by being printed, shared or scanned. Resolution depends on a compatible WalletWall disclosure store or resolver.
 *
 * Two serializations of one value, both deterministic (fixed field names, fixed order, fixed version, no clock, no
 * generated id, no path, no credential, no UI state):
 *
 *   text form (what a QR code encodes and what Copy puts on the clipboard)
 *     walletwall://wallprint/<recordId>?reference=0.1&wallprint=<wallprintVersion>&digest=<hex64>[&target=<target>]
 *
 *   envelope form (structured export), in RFC 8785 key order, a locator envelope and not a second record format
 *     {"digest":"…","recordId":"…","target":"receipt","type":"walletwall.wallprint.reference","version":"0.1","wallprintVersion":"0.1"}
 *
 * and one REPRESENTATION of the text form for a public HTTPS resolver, which is not a third identity: the same text with
 * the scheme and host replaced by a resolver base and the route (`toHttpsUrl`, `parseHttpsUrl`), a prefix substitution
 * that is deterministic and lossless and carries the reference's own versions
 *
 *   https form (what a public page's QR code and share control carry; the base is supplied by the caller, never named here)
 *     <resolverBase>/wallprint/<recordId>?reference=0.1&wallprint=<wallprintVersion>&digest=<hex64>[&target=<target>]
 *
 * Parsing is strict and fails closed: the exact scheme and host, the exact parameter order, no duplicate or unknown
 * parameter, no percent-encoding, no character outside a small ASCII set, no case folding of ids or digests, and a
 * target only from the closed table. A reference that fails to parse reports a fixed outcome and a fixed problem code,
 * never any part of the input. A credential-shaped record id (the one slot free text could hide in) is refused in both
 * directions. Nothing here is imported by main.ts, server.ts or tools.ts; this module is additionally bundled, unchanged,
 * into the canvas (plugin/.../wallprint-reference.mjs, generated by scripts/gen-wallprint-reference.ts), so it imports
 * only vocabulary.ts, errors.ts and language.ts, none of which imports anything else.
 */

export const REFERENCE_VERSION = "0.1";
export const REFERENCE_PREFIX = "walletwall://wallprint/";
export const REFERENCE_ENVELOPE_TYPE = "walletwall.wallprint.reference";
/** The sections a reference may open, in the order the document presents them. `record` is the record itself. */
export const REFERENCE_TARGETS = ["record", "receipt", "replay", "history", "assessments", "provenance"] as const;
export type ReferenceTarget = (typeof REFERENCE_TARGETS)[number];
/** The WallPrint contract versions this codec resolves. A reference to any other version is UNSUPPORTED_VERSION. */
export const SUPPORTED_WALLPRINT_VERSIONS: readonly string[] = Object.freeze([WALLPRINT_VERSION]);
/** Longest text either form can take with the longest record id and target; longer input is refused before parsing. */
export const REFERENCE_MAX_LENGTH = 320;

export const REFERENCE_OUTCOMES = ["RESOLVED", "UNAVAILABLE", "NOT_COMPARED", "DIGEST_MISMATCH", "MALFORMED_REFERENCE", "UNSUPPORTED_VERSION"] as const;
export type ReferenceOutcome = (typeof REFERENCE_OUTCOMES)[number];

/** What a reference identifies. It says nothing about truth, safety or endorsement; a resolver must say so too. */
export const REFERENCE_IDENTIFIES = "This reference identifies the WallPrint record and digest. Resolution depends on a compatible WalletWall disclosure store or resolver.";
export const REFERENCE_DOES_NOT_ESTABLISH: readonly string[] = Object.freeze(["that any claim in the record is true", "the safety of the asset", "issuer endorsement of the record", "who committed the record"]);

export interface WallPrintPortableReference {
  readonly version: typeof REFERENCE_VERSION;
  readonly wallprintVersion: string;
  readonly recordId: string;
  readonly digest: string;
  /** The section to open, or null for the record as a whole. */
  readonly target: ReferenceTarget | null;
}

export interface WallPrintReferenceEnvelope {
  readonly type: typeof REFERENCE_ENVELOPE_TYPE;
  readonly version: typeof REFERENCE_VERSION;
  readonly wallprintVersion: string;
  readonly recordId: string;
  readonly digest: string;
  readonly target?: ReferenceTarget;
}

/** Which fixed part of the input failed. Never a caller value. `resolver`: not this resolver's base and route. */
export type ReferenceProblem = "text" | "length" | "characters" | "scheme" | "query" | "envelope" | "reference" | "wallprint" | "recordId" | "digest" | "target" | "resolver";

export type ReferenceParse = { ok: true; reference: WallPrintPortableReference } | { ok: false; outcome: "MALFORMED_REFERENCE" | "UNSUPPORTED_VERSION"; problem: ReferenceProblem };

/** The facts a store supplies about the record it found for a reference's id, or null when it holds none. */
export interface FoundRecord {
  recordId: string;
  /** The digest the stored record carries in its own `digest` field, or null when it carries none. */
  embeddedDigest: string | null;
  /** The digest the engine computed over the stored record's canonical bytes (verifyWallPrintDigest), or null when it could not be computed. */
  computedDigest: string | null;
}

export type ReferenceResolution =
  | { outcome: "RESOLVED"; recordId: string; digest: string; target: ReferenceTarget | null }
  | { outcome: "UNAVAILABLE"; recordId: string }
  /** The store carries no digest, or no computed digest, for the record: nothing was compared, so nothing is said to match or differ. */
  | { outcome: "NOT_COMPARED"; recordId: string; referenceDigest: string; embeddedDigest: string | null; computedDigest: string | null }
  | { outcome: "DIGEST_MISMATCH"; recordId: string; referenceDigest: string; embeddedDigest: string; computedDigest: string };

// ─── grammar ─────────────────────────────────────────────────────────────────

/** A version in its one canonical spelling: no leading zero, so `00.1` and `0.10` are not versions. */
const VERSION_RE = /^(0|[1-9][0-9]{0,3})\.(0|[1-9][0-9]{0,3})$/;
/** Every character the text form can contain. Anything else (space, %, #, +, @, quotes, control or non-ASCII) is refused. */
const TEXT_CHARS_RE = /^[A-Za-z0-9:/?&=._-]+$/;
/** The envelope form adds the JSON punctuation of a flat object of strings; no whitespace and no backslash, since only the canonical text is admitted. */
const ENVELOPE_CHARS_RE = /^[A-Za-z0-9:/?&=._{}",-]+$/;
const ENVELOPE_KEYS = ["digest", "recordId", "target", "type", "version", "wallprintVersion"] as const;
const TARGET_SET: ReadonlySet<string> = new Set(REFERENCE_TARGETS);
/** An EVM address is an identity, never a record id: a reference must not be able to carry one in the id slot. */
const ADDRESS_SHAPED_ID_RE = /^0x[0-9a-f]{40}$/;

const isTarget = (v: unknown): v is ReferenceTarget => typeof v === "string" && TARGET_SET.has(v);
const bad = (outcome: "MALFORMED_REFERENCE" | "UNSUPPORTED_VERSION", problem: ReferenceProblem): ReferenceParse => ({ ok: false, outcome, problem });
/**
 * A record id a reference may carry: the record's own shape, and additionally not address-shaped, not credential-shaped
 * and free of the reserved assurance terms, because a well-formed but unknown id is the one caller value a resolver may
 * print back ("Record unavailable") and must therefore never read as an address, a secret or a verdict.
 */
const admissibleRecordId = (id: string): boolean => RECORD_ID_RE.test(id) && !ADDRESS_SHAPED_ID_RE.test(id) && findSecretLike(id) === null && findReservedAssuranceTerms(id).length === 0;

/** The findings for a reference's fields; empty when every field has its fixed shape. */
export function referenceFindings(ref: unknown): Finding[] {
  const out: Finding[] = [];
  if (ref === null || typeof ref !== "object" || Array.isArray(ref)) return [finding("INVALID_TYPE", "")];
  const r = ref as Record<string, unknown>;
  if (r["version"] !== REFERENCE_VERSION) out.push(finding("UNSUPPORTED_VERSION", "version"));
  if (typeof r["wallprintVersion"] !== "string" || !VERSION_RE.test(r["wallprintVersion"])) out.push(finding("INVALID_FORMAT", "wallprintVersion"));
  else if (!SUPPORTED_WALLPRINT_VERSIONS.includes(r["wallprintVersion"])) out.push(finding("UNSUPPORTED_VERSION", "wallprintVersion"));
  if (typeof r["recordId"] !== "string" || !RECORD_ID_RE.test(r["recordId"]) || ADDRESS_SHAPED_ID_RE.test(r["recordId"])) out.push(finding("INVALID_ID", "recordId"));
  else if (findSecretLike(r["recordId"]) !== null) out.push(finding("SUSPECTED_SECRET", "recordId"));
  else if (findReservedAssuranceTerms(r["recordId"]).length > 0) out.push(finding("MANUFACTURED_ASSURANCE", "recordId"));
  if (typeof r["digest"] !== "string" || !HEX64_RE.test(r["digest"])) out.push(finding("INVALID_DIGEST", "digest"));
  if (r["target"] !== null && !isTarget(r["target"])) out.push(finding("INVALID_ENUM", "target"));
  for (const k of Object.keys(r)) if (!["version", "wallprintVersion", "recordId", "digest", "target"].includes(k)) out.push(finding("UNKNOWN_FIELD", ""));
  return out;
}

function assertReference(ref: unknown): asserts ref is WallPrintPortableReference {
  const findings = referenceFindings(ref);
  if (findings.length > 0) throw new WallPrintError("INVALID_REFERENCE", findings);
}

/** A frozen plain reference from its parts, or null when a part has no fixed shape. Never throws. */
export function tryReference(parts: { recordId: unknown; digest: unknown; wallprintVersion: unknown }, target: unknown = null): WallPrintPortableReference | null {
  const candidate = { version: REFERENCE_VERSION, wallprintVersion: parts.wallprintVersion, recordId: parts.recordId, digest: parts.digest, target };
  return referenceFindings(candidate).length === 0 ? Object.freeze(candidate as WallPrintPortableReference) : null;
}

/** The reference for a record: its id, its digest and its WallPrint version. Throws INVALID_REFERENCE when a part has no fixed shape. */
export function referenceOf(record: { id: unknown; digest: unknown; wallprintVersion: unknown }, target: ReferenceTarget | null = null): WallPrintPortableReference {
  const ref = tryReference({ recordId: record.id, digest: record.digest, wallprintVersion: record.wallprintVersion }, target);
  if (ref === null) throw new WallPrintError("INVALID_REFERENCE", referenceFindings({ version: REFERENCE_VERSION, wallprintVersion: record.wallprintVersion, recordId: record.id, digest: record.digest, target }));
  return ref;
}

// ─── text form ───────────────────────────────────────────────────────────────

/** The text form. Deterministic: the same reference always encodes to the same string. Throws INVALID_REFERENCE. */
export function encodeReference(ref: WallPrintPortableReference): string {
  assertReference(ref);
  return `${REFERENCE_PREFIX}${ref.recordId}?reference=${ref.version}&wallprint=${ref.wallprintVersion}&digest=${ref.digest}${ref.target === null ? "" : `&target=${ref.target}`}`;
}

function parseText(text: string): ReferenceParse {
  if (!TEXT_CHARS_RE.test(text)) return bad("MALFORMED_REFERENCE", "characters");
  if (!text.startsWith(REFERENCE_PREFIX)) return bad("MALFORMED_REFERENCE", "scheme");
  const rest = text.slice(REFERENCE_PREFIX.length);
  const q = rest.indexOf("?");
  if (q < 0) return bad("MALFORMED_REFERENCE", "query");
  const recordId = rest.slice(0, q);
  const pairs = rest
    .slice(q + 1)
    .split("&")
    .map((pair) => {
      const i = pair.indexOf("=");
      return i < 0 ? null : ([pair.slice(0, i), pair.slice(i + 1)] as const);
    });
  const keys = pairs.map((p) => (p === null ? "" : p[0]));
  // Exactly the fixed parameters in the fixed order; a value never contains "=" and no parameter repeats.
  const expected = keys.length === 4 ? ["reference", "wallprint", "digest", "target"] : ["reference", "wallprint", "digest"];
  if (keys.length !== expected.length || keys.some((k, i) => k !== expected[i]) || pairs.some((p) => p === null || p[1].includes("="))) {
    // The version comes first so an unsupported reference version is reported as such even when the rest of its grammar differs.
    const first = pairs[0];
    if (first !== null && first !== undefined && first[0] === "reference" && VERSION_RE.test(first[1]) && first[1] !== REFERENCE_VERSION) return bad("UNSUPPORTED_VERSION", "reference");
    return bad("MALFORMED_REFERENCE", "query");
  }
  const version = pairs[0]![1];
  const wallprintVersion = pairs[1]![1];
  const digest = pairs[2]![1];
  const target = pairs[3]?.[1];
  if (!VERSION_RE.test(version)) return bad("MALFORMED_REFERENCE", "reference");
  if (version !== REFERENCE_VERSION) return bad("UNSUPPORTED_VERSION", "reference");
  if (!VERSION_RE.test(wallprintVersion)) return bad("MALFORMED_REFERENCE", "wallprint");
  if (!SUPPORTED_WALLPRINT_VERSIONS.includes(wallprintVersion)) return bad("UNSUPPORTED_VERSION", "wallprint");
  if (!admissibleRecordId(recordId)) return bad("MALFORMED_REFERENCE", "recordId");
  if (!HEX64_RE.test(digest)) return bad("MALFORMED_REFERENCE", "digest");
  if (target !== undefined && !isTarget(target)) return bad("MALFORMED_REFERENCE", "target");
  return { ok: true, reference: Object.freeze({ version: REFERENCE_VERSION, wallprintVersion, recordId, digest, target: target ?? null }) };
}

// ─── envelope form ───────────────────────────────────────────────────────────

/** The locator envelope: the reference's fields plus a type tag. Not a record format. */
export function referenceEnvelope(ref: WallPrintPortableReference): WallPrintReferenceEnvelope {
  assertReference(ref);
  const envelope: WallPrintReferenceEnvelope = ref.target === null
    ? { type: REFERENCE_ENVELOPE_TYPE, version: ref.version, wallprintVersion: ref.wallprintVersion, recordId: ref.recordId, digest: ref.digest }
    : { type: REFERENCE_ENVELOPE_TYPE, version: ref.version, wallprintVersion: ref.wallprintVersion, recordId: ref.recordId, digest: ref.digest, target: ref.target };
  return Object.freeze(envelope);
}

/**
 * The envelope as text, in RFC 8785 form (keys in UTF-16 order, no whitespace, strings escaped as JSON). Every value is
 * a plain ASCII string, so this equals the engine's canonicalize() of the envelope (pinned by test).
 */
export function encodeReferenceEnvelope(ref: WallPrintPortableReference): string {
  const e: Readonly<Record<string, string | undefined>> = { ...referenceEnvelope(ref) };
  return `{${ENVELOPE_KEYS.filter((k) => e[k] !== undefined)
    .map((k) => `${JSON.stringify(k)}:${JSON.stringify(e[k])}`)
    .join(",")}}`;
}

/** Strict parse of an envelope value (a plain object): exactly the fixed keys, every value a string of its fixed shape. */
export function parseReferenceEnvelope(value: unknown): ReferenceParse {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return bad("MALFORMED_REFERENCE", "envelope");
  const proto: unknown = Object.getPrototypeOf(value);
  if (proto !== Object.prototype && proto !== null) return bad("MALFORMED_REFERENCE", "envelope");
  const e = value as Record<string, unknown>;
  const keys = Object.getOwnPropertyNames(e).sort();
  const withTarget = keys.includes("target");
  const expected = ENVELOPE_KEYS.filter((k) => withTarget || k !== "target");
  if (keys.length !== expected.length || keys.some((k, i) => k !== expected[i])) return bad("MALFORMED_REFERENCE", "envelope");
  for (const k of expected) if (typeof e[k] !== "string") return bad("MALFORMED_REFERENCE", "envelope");
  if (e["type"] !== REFERENCE_ENVELOPE_TYPE) return bad("MALFORMED_REFERENCE", "envelope");
  const version = e["version"] as string;
  const wallprintVersion = e["wallprintVersion"] as string;
  const recordId = e["recordId"] as string;
  const digest = e["digest"] as string;
  if (!VERSION_RE.test(version)) return bad("MALFORMED_REFERENCE", "reference");
  if (version !== REFERENCE_VERSION) return bad("UNSUPPORTED_VERSION", "reference");
  if (!VERSION_RE.test(wallprintVersion)) return bad("MALFORMED_REFERENCE", "wallprint");
  if (!SUPPORTED_WALLPRINT_VERSIONS.includes(wallprintVersion)) return bad("UNSUPPORTED_VERSION", "wallprint");
  if (!admissibleRecordId(recordId)) return bad("MALFORMED_REFERENCE", "recordId");
  if (!HEX64_RE.test(digest)) return bad("MALFORMED_REFERENCE", "digest");
  const target = withTarget ? e["target"] : null;
  if (target !== null && !isTarget(target)) return bad("MALFORMED_REFERENCE", "target");
  return { ok: true, reference: Object.freeze({ version: REFERENCE_VERSION, wallprintVersion, recordId, digest, target }) };
}

// ─── parse (either form) ─────────────────────────────────────────────────────

/**
 * Parse a portable reference as scanned, pasted or copied: the text form, or the envelope as JSON text. Strict, fail
 * closed, never throws, never echoes the input: the result carries a fixed outcome and a fixed problem code. Each form
 * has exactly one admitted spelling: the envelope text must be the canonical text its own fields encode to (no
 * whitespace, no reordered or repeated key), so one value never has two spellings on input either.
 */
export function parseReference(input: unknown): ReferenceParse {
  if (typeof input !== "string" || input === "") return bad("MALFORMED_REFERENCE", "text");
  if (input.length > REFERENCE_MAX_LENGTH) return bad("MALFORMED_REFERENCE", "length");
  if (input.startsWith("{")) {
    if (!ENVELOPE_CHARS_RE.test(input)) return bad("MALFORMED_REFERENCE", "characters");
    // JSON.parse keeps the last of two equal keys; an envelope text that names a key twice is refused before parsing,
    // exactly as the text form refuses a repeated parameter. The charset admits no escape, so a key is one literal run.
    for (const k of ENVELOPE_KEYS) if ((input.match(new RegExp(`"${k}":`, "g")) ?? []).length > 1) return bad("MALFORMED_REFERENCE", "envelope");
    let value: unknown;
    try {
      value = JSON.parse(input);
    } catch {
      return bad("MALFORMED_REFERENCE", "envelope");
    }
    const parsed = parseReferenceEnvelope(value);
    if (parsed.ok && encodeReferenceEnvelope(parsed.reference) !== input) return bad("MALFORMED_REFERENCE", "envelope");
    return parsed;
  }
  return parseText(input);
}

// ─── https form ──────────────────────────────────────────────────────────────

/** The route a public resolver serves references under. The text form's `walletwall://wallprint/` maps onto `<base>/wallprint/`. */
export const RESOLVER_ROUTE = "/wallprint/";
/** A dotted DNS host in lower case whose last label is alphabetic: never an IP literal, a single label or a non-ASCII name. (`host` equals the name alone once the port is required to be empty.) */
const RESOLVER_HOST_RE = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
/** No internationalised label either: a resolver base reads the same to a reader and to a machine, so look-alike bases are refused. */
const PUNYCODE_LABEL_RE = /(?:^|\.)xn--/;
const RESOLVER_BASE_MAX_LENGTH = 256;

/**
 * True for exactly one spelling of an HTTPS origin: the base equals its own parsed origin (so it carries no path, query,
 * fragment, userinfo or default port and no upper-case letter), its scheme is HTTPS and its host is a dotted DNS name.
 * No base is named in this module: a resolver base is a caller value, checked, never assumed.
 */
export function isResolverBase(base: unknown): base is string {
  if (typeof base !== "string" || base === "" || base.length > RESOLVER_BASE_MAX_LENGTH) return false;
  let parsed: URL;
  try {
    parsed = new URL(base);
  } catch {
    return false;
  }
  return parsed.origin === base && parsed.protocol === "https:" && parsed.port === "" && RESOLVER_HOST_RE.test(parsed.host) && !PUNYCODE_LABEL_RE.test(parsed.host);
}

/** The reference's path and query under the route: the text form with `walletwall://wallprint/` replaced by `/wallprint/`. Throws INVALID_REFERENCE. */
export function toResolverPath(ref: WallPrintPortableReference): string {
  return `${RESOLVER_ROUTE}${encodeReference(ref).slice(REFERENCE_PREFIX.length)}`;
}

/** The public HTTPS form: the resolver base plus the resolver path. Throws INVALID_REFERENCE for an invalid base (finding INVALID_RESOLVER_BASE) or reference. */
export function toHttpsUrl(ref: WallPrintPortableReference, resolverBase: string): string {
  if (!isResolverBase(resolverBase)) throw new WallPrintError("INVALID_REFERENCE", [finding("INVALID_RESOLVER_BASE", "resolverBase")]);
  return `${resolverBase}${toResolverPath(ref)}`;
}

/**
 * Parse a path and query as a public resolver receives it (`/wallprint/<recordId>?…`): the route is required exactly, and
 * the rest is read by the text form's own strict grammar after the prefix substitution is undone. Never throws, never echoes.
 */
export function parseResolverPath(pathAndQuery: unknown): ReferenceParse {
  if (typeof pathAndQuery !== "string" || pathAndQuery === "") return bad("MALFORMED_REFERENCE", "text");
  if (pathAndQuery.length > REFERENCE_MAX_LENGTH) return bad("MALFORMED_REFERENCE", "length");
  if (!pathAndQuery.startsWith(RESOLVER_ROUTE)) return bad("MALFORMED_REFERENCE", "resolver");
  return parseReference(`${REFERENCE_PREFIX}${pathAndQuery.slice(RESOLVER_ROUTE.length)}`);
}

/** Parse a public HTTPS URL against one resolver base: the base and the route must match exactly; the rest is the text form's grammar. Never throws, never echoes. */
export function parseHttpsUrl(url: unknown, resolverBase: unknown): ReferenceParse {
  if (!isResolverBase(resolverBase)) return bad("MALFORMED_REFERENCE", "resolver");
  if (typeof url !== "string" || url === "") return bad("MALFORMED_REFERENCE", "text");
  if (url.length > resolverBase.length + REFERENCE_MAX_LENGTH) return bad("MALFORMED_REFERENCE", "length");
  if (!url.startsWith(`${resolverBase}${RESOLVER_ROUTE}`)) return bad("MALFORMED_REFERENCE", "resolver");
  return parseResolverPath(url.slice(resolverBase.length));
}

// ─── resolution ──────────────────────────────────────────────────────────────

/**
 * Resolve a parsed reference against what a store found for its record id. The store looks the record up by id (any
 * committed version: a corrected, superseded or withdrawn record is a valid target) and reports the digest the record
 * carries and the digest the engine computed over its bytes; this function compares and decides nothing else.
 *
 *   UNAVAILABLE      no record with that id is available here (not invalid, not false: this store does not hold it)
 *   NOT_COMPARED     the store carries no digest, or no computed digest, for the record: nothing was compared, so
 *                    nothing is said to match or to differ (absence is absence, never a mismatch)
 *   DIGEST_MISMATCH  both digests were compared and the resolved record does not match the digest carried by the
 *                    reference (which record is the committed one is not decided here; every digest is reported)
 *   RESOLVED         the record carries the reference's digest and the engine computed that digest over its bytes
 */
export function resolveReference(ref: WallPrintPortableReference, found: FoundRecord | null): ReferenceResolution {
  assertReference(ref);
  if (found === null || found.recordId !== ref.recordId) return { outcome: "UNAVAILABLE", recordId: ref.recordId };
  const embedded = typeof found.embeddedDigest === "string" && HEX64_RE.test(found.embeddedDigest) ? found.embeddedDigest : null;
  const computed = typeof found.computedDigest === "string" && HEX64_RE.test(found.computedDigest) ? found.computedDigest : null;
  if (embedded === null || computed === null) return { outcome: "NOT_COMPARED", recordId: ref.recordId, referenceDigest: ref.digest, embeddedDigest: embedded, computedDigest: computed };
  if (embedded === ref.digest && computed === ref.digest) return { outcome: "RESOLVED", recordId: ref.recordId, digest: ref.digest, target: ref.target };
  return { outcome: "DIGEST_MISMATCH", recordId: ref.recordId, referenceDigest: ref.digest, embeddedDigest: embedded, computedDigest: computed };
}

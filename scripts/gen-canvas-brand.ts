import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Embeds the WalletWall brand assets in canvas/brand/ (fonts, the brick-wallet mark, the WalletWallaby guide poses) into the
 * canvas as one text module of data: URIs. The canvas page therefore needs no font, image or CDN request, and the plugin
 * stays plain text. Every file must match the SHA-256 recorded in canvas/brand/brand-sources.json.
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const brandDir = `${root}canvas/brand`;
const outPath = `${root}plugin/com.github.copilot/extensions/walletwall-evidence-explorer/brand.mjs`;

interface Asset {
  file: string;
  sha256: string;
  role: string;
}
interface Font extends Asset {
  family: string;
  weight: string;
  format: string;
  package: string;
  version: string;
  license: string;
}
const sources = JSON.parse(readFileSync(`${brandDir}/brand-sources.json`, "utf8")) as { images: Asset[]; fonts: Font[] };

function bytesOf(a: Asset): Buffer {
  const bytes = readFileSync(`${brandDir}/${a.file}`);
  const actual = createHash("sha256").update(bytes).digest("hex");
  if (actual !== a.sha256) {
    console.error(`canvas/brand/${a.file}: sha256 ${actual} does not match brand-sources.json (${a.sha256})`);
    process.exit(1);
  }
  return bytes;
}

const fontFaces = sources.fonts
  .map((f) => `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${f.weight};font-display:block;src:url(data:font/woff2;base64,${bytesOf(f).toString("base64")}) format("${f.format}")}`)
  .join("\n");
const image = (file: string): string => {
  const a = sources.images.find((x) => x.file === file);
  if (!a) throw new Error(`${file} is not listed in brand-sources.json`);
  return `data:image/png;base64,${bytesOf(a).toString("base64")}`;
};

const text = `// GENERATED by scripts/gen-canvas-brand.ts from canvas/brand/ (see canvas/brand/brand-sources.json). Do not edit; run: npm run gen:canvas-brand
// WalletWall brand assets as data: URIs, so the canvas page loads no font, image or stylesheet from anywhere.
// Fonts: ${sources.fonts.map((f) => `${f.package}@${f.version} ${f.weight} (${f.license})`).join("; ")}. License texts: plugin/THIRD_PARTY_NOTICES.md.

export const FONT_FAMILIES = ${JSON.stringify(Object.fromEntries(sources.fonts.map((f) => [f.family, f.package])))};

export const FONT_FACES = ${JSON.stringify(fontFaces)};

export const MARK = ${JSON.stringify(image("walletwall-brick-wallet-96.png"))};

export const WALLABY = {
  inspect: ${JSON.stringify(image("walletwallaby-inspect.png"))},
  perch: ${JSON.stringify(image("walletwallaby-perch.png"))},
};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // reported below
  }
  if (current !== text) {
    console.error("Canvas brand module is out of date. Run: npm run gen:canvas-brand");
    process.exit(1);
  }
  console.log(`canvas brand assets current: ${sources.fonts.length} fonts, ${sources.images.length} images`);
} else {
  writeFileSync(outPath, text);
  console.log(`wrote brand.mjs: ${sources.fonts.length} fonts, ${sources.images.length} images (${Math.round(text.length / 1024)} KiB)`);
}

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { bundleOptions } from "./bundle-config.ts";

/**
 * Third-party license notices for the shipped MCP server bundle. The bundle is built with `legalComments: "none"`, so the
 * copyright and permission notices of the bundled packages are not inside it; this file carries them next to it.
 * The package list comes from the bundle's own module graph, so it cannot drift from what is actually shipped.
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const outFile = `${root}plugin/THIRD_PARTY_NOTICES.md`;
const check = process.argv.includes("--check");

const result = await build(bundleOptions(root));
const names = new Set<string>();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input.replaceAll("\\", "/"));
  if (m?.[1]) names.add(m[1]);
}

const LICENSE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "license.md"];
const sections: string[] = [];
for (const name of [...names].sort()) {
  const dir = `${root}node_modules/${name}`;
  const pkg = JSON.parse(readFileSync(`${dir}/package.json`, "utf8")) as { version: string; license?: string };
  const file = LICENSE_FILES.map((f) => `${dir}/${f}`).find((f) => existsSync(f));
  if (file === undefined || pkg.license === undefined) {
    console.error(`No license file or license field for bundled package ${name}`);
    process.exit(1);
  }
  const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim();
  sections.push(`## ${name} ${pkg.version} (${pkg.license})\n\n\`\`\`text\n${text}\n\`\`\``);
}

const fontSources = JSON.parse(readFileSync(`${root}canvas/brand/brand-sources.json`, "utf8")) as { fonts: { family: string; package: string; version: string; license: string; licenseFile: string; file: string; weight: string }[] };
const fontSections: string[] = [];
for (const licenseFile of [...new Set(fontSources.fonts.map((f) => f.licenseFile))]) {
  const fonts = fontSources.fonts.filter((f) => f.licenseFile === licenseFile);
  const first = fonts[0]!;
  const text = readFileSync(`${root}canvas/brand/${licenseFile}`, "utf8").replace(/\r\n/g, "\n").trim();
  const files = fonts.map((f) => `\`${f.file.replace(/^fonts\//, "")}\` (weight ${f.weight})`).join(", ");
  fontSections.push(`## ${first.family}, from ${first.package} ${first.version} (${first.license})\n\nEmbedded files: ${files}.\n\n\`\`\`text\n${text}\n\`\`\``);
}

const doc = `# Third-party notices

The WalletWall MCP server bundle \`server/walletwall-mcp.mjs\` contains code from the packages listed below. Each is used under its own license, reproduced here. WalletWall's own code is licensed under the Apache License 2.0 (\`LICENSE\`); that license does not change the terms of these packages.

This file is generated by \`npm run gen:notices\` from the bundle's module graph and checked by \`npm run verify:notices\`. Do not edit it by hand.

${sections.join("\n\n")}

# Fonts embedded in the WalletWall canvas

The canvas (\`com.github.copilot/extensions/walletwall-evidence-explorer/brand.mjs\`) embeds the latin subsets of the fonts below, unmodified, so that it never requests a font from the network. Each font is used under the SIL Open Font License 1.1, reproduced here with its copyright notice. The font list comes from \`canvas/brand/brand-sources.json\`.

${fontSections.join("\n\n")}
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // reported below
  }
  if (current !== doc) {
    console.error("plugin/THIRD_PARTY_NOTICES.md is out of date. Run: npm run gen:notices");
    process.exit(1);
  }
  console.log(`third-party notices current: ${names.size} bundled packages`);
} else {
  writeFileSync(outFile, doc);
  console.log(`wrote plugin/THIRD_PARTY_NOTICES.md for ${names.size} bundled packages: ${[...names].sort().join(", ")}`);
}

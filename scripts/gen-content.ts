import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const spec = readFileSync(`${root}spec/EVIDENCE_PROFILE.md`, "utf8").replace(/\r\n/g, "\n");
const out =
  `// GENERATED by scripts/gen-content.ts from spec/EVIDENCE_PROFILE.md. Do not edit.\n` +
  `export const SPEC_WWEP_MD: string = ${JSON.stringify(spec)};\n`;
const target = `${root}packages/mcp/src/generated/content.ts`;

if (process.argv.includes("--check")) {
  let current: string;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    current = "";
  }
  if (current !== out) {
    console.error("generated/content.ts is out of date. Run: npm run gen:content");
    process.exit(1);
  }
  console.log("generated/content.ts is up to date");
} else {
  writeFileSync(target, out);
  console.log("wrote packages/mcp/src/generated/content.ts");
}

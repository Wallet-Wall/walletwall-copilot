import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { evaluateBundle } from "../packages/mcp/src/evaluate.ts";
import { assessReadiness } from "../packages/mcp/src/readiness.ts";
import { BundleSchema } from "../packages/mcp/src/schemas.ts";
import { callTool } from "../packages/mcp/src/tools.ts";
import { CASES } from "../packages/mcp/test/support/cases.ts";

/**
 * Synthetic, deterministic bundles for the Evidence Explorer, taken from the WWEP conformance corpus so they are
 * exactly the inputs the conformance suite already proves. They contain no real wallet addresses.
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const outPath = `${root}plugin/com.github.copilot/extensions/walletwall-evidence-explorer/fixtures.mjs`;

const byId = (id: string) => {
  const c = CASES.find((x) => x.id === id);
  if (!c) throw new Error(`conformance case ${id} not found`);
  return c;
};

/** Appends the readiness derivation and assertion the engine itself suggests for the identity and balance assertions. */
function withReadiness(bundleIn: unknown, evaluatedAt: string): unknown {
  const bundle = BundleSchema.parse(bundleIn);
  const r = assessReadiness(bundle, evaluateBundle(bundle, evaluatedAt), "a-identity", "a-balance");
  bundle.derivations.push(r.suggestedDerivation);
  bundle.assertions.push(r.suggestedAssertion);
  return bundle;
}

const established = structuredClone(byId("EVD-001"));
established.bundle = withReadiness(established.bundle, established.evaluatedAt);

// The same synthetic USDC bundle, but the balance comes from a single provider endpoint instead of canonical chain state:
// the balance is PARTIAL, so the readiness criteria cannot all be met.
const blocked = structuredClone(byId("EVD-001"));
{
  const b = BundleSchema.parse(blocked.bundle);
  b.observations = b.observations.map((o) => (o.id === "obs-balance" ? { ...o, sourceId: "src-prov-a", origin: "PROVIDER_OBSERVED" as const, finality: "UNKNOWN_FINALITY" as const } : o));
  b.assertions = b.assertions.map((a) => (a.id === "a-balance" ? { ...a, origin: "PROVIDER_OBSERVED" as const } : a));
  blocked.bundle = withReadiness(b, blocked.evaluatedAt);
}

const fixtures = {
  "usdc-established": {
    title: "Synthetic USDC identity attested by the issuer and a finalized balance, with the readiness assertion derived from them (conformance EVD-001 plus derived readiness).",
    from: "EVD-001",
    evaluatedAt: established.evaluatedAt,
    bundle: established.bundle,
  },
  "stale-identity": {
    title: "Identity evidence is older than the policy allows, so the derived readiness assertion is STALE (conformance FRS-009).",
    from: "FRS-009",
    evaluatedAt: byId("FRS-009").evaluatedAt,
    bundle: byId("FRS-009").bundle,
  },
  "conflicting-balances": {
    title: "Two chain observations disagree about the balance, and the conflict propagates to readiness (conformance CNF-004).",
    from: "CNF-004",
    evaluatedAt: byId("CNF-004").evaluatedAt,
    bundle: byId("CNF-004").bundle,
  },
  "partial-provider-balance": {
    title: "A single provider-reported balance is PARTIAL and never established (conformance AUT-002).",
    from: "AUT-002",
    evaluatedAt: byId("AUT-002").evaluatedAt,
    bundle: byId("AUT-002").bundle,
  },
  "unknown-balance": {
    title: "The chain source returned no result. The balance is UNKNOWN, not zero, and the bundle's zero value is flagged (conformance EVD-008).",
    from: "EVD-008",
    evaluatedAt: byId("EVD-008").evaluatedAt,
    bundle: byId("EVD-008").bundle,
  },
  "superseded-balance": {
    title: "A newer balance supersedes the older one; the old assertion stays in the bundle as SUPERSEDED (conformance CNF-005).",
    from: "CNF-005",
    evaluatedAt: byId("CNF-005").evaluatedAt,
    bundle: byId("CNF-005").bundle,
  },
  "readiness-blocked": {
    title: "Synthetic USDC identity is established but the balance comes from one provider endpoint, so it is PARTIAL and the readiness criteria are not all met (EVD-001 with a provider-reported balance, plus derived readiness).",
    from: "EVD-001",
    evaluatedAt: blocked.evaluatedAt,
    bundle: blocked.bundle,
  },
};

for (const [name, f] of Object.entries(fixtures)) {
  const r = callTool("inspect_evidence", { bundle: f.bundle, evaluatedAt: f.evaluatedAt });
  if (!r.ok) throw new Error(`fixture ${name} is not accepted by the engine`);
}

const text = `// GENERATED by scripts/gen-canvas-fixtures.ts from the WWEP conformance corpus. Do not edit; run: npm run gen:canvas
// Synthetic evidence only. No real wallet address, balance or user data.
export const FIXTURES = ${JSON.stringify(fixtures, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // reported below
  }
  if (current !== text) {
    console.error("Evidence Explorer fixtures are out of date. Run: npm run gen:canvas");
    process.exit(1);
  }
  console.log(`canvas fixtures current: ${Object.keys(fixtures).length} bundles`);
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${Object.keys(fixtures).length} fixtures`);
}

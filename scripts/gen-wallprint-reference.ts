import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * The portable reference codec the canvas runs is the canonical module packages/mcp/src/wallprint/reference.ts, bundled
 * unchanged (with the three dependency-free modules it imports: vocabulary, errors, language) into one plain ES module
 * for the plugin, which ships no TypeScript. The output is deterministic for a given esbuild version, so `--check`
 * proves the shipped file is exactly the build of the canonical source. Nothing else is bundled: no zod, no engine
 * module, no node: import.
 *
 *   npm run gen:wallprint-reference        regenerate
 *   npm run verify:wallprint-reference     check the shipped file is current
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const entry = "packages/mcp/src/wallprint/reference.ts";
const outPath = `${root}plugin/com.github.copilot/extensions/walletwall-evidence-explorer/wallprint-reference.mjs`;

const result = await build({
  absWorkingDir: root,
  entryPoints: [entry],
  bundle: true,
  platform: "neutral",
  format: "esm",
  target: "es2023",
  write: false,
  metafile: true,
  legalComments: "none",
  logLevel: "warning",
  treeShaking: true,
});

const inputs = Object.keys(result.metafile.inputs).map((p) => p.replaceAll("\\", "/")).sort();
const allowed = ["packages/mcp/src/wallprint/errors.ts", "packages/mcp/src/wallprint/language.ts", "packages/mcp/src/wallprint/reference.ts", "packages/mcp/src/wallprint/vocabulary.ts"];
if (inputs.join("|") !== allowed.join("|")) throw new Error(`the reference codec bundle must contain exactly ${allowed.join(", ")}; got ${inputs.join(", ")}`);

const body = (result.outputFiles[0]?.text ?? "").replace(/\r\n/g, "\n");
if (/\bimport\s|\brequire\(|node:|process\.|Date\.|Math\.random|\bfetch\(|\beval\(|\bFunction\(|globalThis|XMLHttpRequest|WebSocket|EventSource|\bWorker\b|localStorage|sessionStorage|indexedDB|document\.|window\./.test(body)) {
  throw new Error("the reference codec bundle must be self-contained and inert");
}

const text = `// GENERATED by scripts/gen-wallprint-reference.ts from the canonical WallPrint portable reference codec
// (packages/mcp/src/wallprint/reference.ts, with the dependency-free vocabulary, errors and language modules it imports),
// bundled unchanged by esbuild. Do not edit; run: npm run gen:wallprint-reference
//
// A portable reference is a locator for one committed WallPrint record: which record, which bytes, which contract
// version, which section. It is not authority. The canvas parses and encodes references with this module and computes
// nothing else: resolution compares the reference's digest with the digests the engine recorded in the fixture.
${body}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // reported below
  }
  if (current !== text) {
    console.error("The canvas's WallPrint reference codec is out of date. Run: npm run gen:wallprint-reference");
    process.exit(1);
  }
  console.log(`wallprint reference codec current: ${inputs.length} source modules, ${text.length} bytes`);
} else {
  writeFileSync(outPath, text);
  console.log(`wrote wallprint-reference.mjs (${Math.round(text.length / 1024)} KiB) from ${inputs.length} source modules`);
}

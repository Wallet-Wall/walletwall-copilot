import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { WALLPRINT_FIXTURE_NAMES, buildWallPrintDisclosures, wallPrintVocabulary } from "../packages/mcp/test/support/wallprint-disclosures.ts";

/**
 * Synthetic, deterministic WallPrint disclosure lineages for the canvas's WallPrint view, produced by the canonical
 * WallPrint engine (record, history, receipt, replay, diff). The disclosure page renders these engine outputs and decides
 * nothing: no evidence state, lifecycle state, receipt or replay verdict is authored here or in the page.
 */
const root = fileURLToPath(new URL("..", import.meta.url));
const outPath = `${root}plugin/com.github.copilot/extensions/walletwall-evidence-explorer/wallprint-fixtures.mjs`;

const fixtures = buildWallPrintDisclosures();
const names = Object.keys(fixtures);
if (names.join("|") !== WALLPRINT_FIXTURE_NAMES.join("|")) throw new Error("fixture names drifted from WALLPRINT_FIXTURE_NAMES");

const text = `// GENERATED by scripts/gen-wallprint-fixtures.ts from the canonical WallPrint engine (packages/mcp/src/wallprint). Do not edit; run: npm run gen:wallprint
// Synthetic disclosure lineages only: records, lifecycle events, receipts, replay results and semantic diffs as the engine produced them.
// No real wallet address, balance or user data. The WallPrint view renders these outputs and computes nothing.

// The engine's own vocabulary and boundary statements, so the page quotes them instead of restating them.
export const WALLPRINT_VOCABULARY = ${JSON.stringify(wallPrintVocabulary(), null, 2)};

export const WALLPRINT_FIXTURES = ${JSON.stringify(fixtures, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // reported below
  }
  if (current !== text) {
    console.error("WallPrint disclosure fixtures are out of date. Run: npm run gen:wallprint");
    process.exit(1);
  }
  console.log(`wallprint fixtures current: ${names.length} lineages, ${names.reduce((n, k) => n + (fixtures[k]?.records.length ?? 0), 0)} records`);
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${names.length} wallprint fixtures (${Math.round(text.length / 1024)} KiB)`);
}
